package storage

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// The three units that make a loop-backed volume survive a reboot.
//
// This is the part that has to be right the first time: a volume that does not
// come back after a reboot does not fail loudly. It leaves /var/stack/data as an
// ordinary empty directory on the root filesystem, and every application starts
// against it. The docker drop-in is what converts that silent corruption into a
// visible, recoverable failure.
//
// Deliberately NOT an /etc/fstab entry. fstab's `nofail` would do exactly the
// wrong thing here, and without it a missing loop device at boot drops the
// system into emergency mode for a data volume — neither is acceptable, and a
// native mount unit expresses the ordering we actually need.

// UnitFiles renders the units for a spec. Exported so the wizard can show what
// it is about to install and so tests can assert the ordering.
func UnitFiles(spec Spec) map[string]string {
	spec = spec.withDefaults()
	files := map[string]string{DefaultMountUnit: mountUnit(spec)}
	if spec.Mode == ModeLoop {
		files[DefaultLoopUnit] = loopUnit(spec)
	}
	files["docker.service.d/pmcluster-data.conf"] = dockerDropIn(spec)
	files["pmcluster.service.d/pmcluster-data.conf"] = consumerDropIn(spec, "the pmcluster daemon")
	files["pmcluster-backup.service.d/pmcluster-data.conf"] = consumerDropIn(spec, "the backup agent")
	return files
}

// loopUnit attaches the backing file and activates the volume group.
func loopUnit(spec Spec) string {
	return fmt.Sprintf(`[Unit]
# Generated by pmcluster. Do not edit: `+"`pmcluster storage provision`"+` rewrites this file.
Description=pmcluster app-data thin pool (loop-backed)
Documentation=https://github.com/hazemarian/poor-man-cluster
DefaultDependencies=no
# The backing file lives under /var, which may be a filesystem of its own (it is
# on Fedora CoreOS, and on any server with /var on a separate LV). local-fs.target
# is what mounts it, so this service must run AFTER it — before that, the path
# exists only as an empty directory on the root filesystem and the backing file
# is invisible.
#
# The mount unit below is therefore also after local-fs.target rather than before
# it: a volume cannot be mounted before the filesystem that holds its backing
# file. Consumers are ordered behind it explicitly (RequiresMountsFor in the
# docker, daemon and backup units) instead of relying on local-fs ordering.
After=local-fs.target
Requires=local-fs.target
Before=%s docker.service pmcluster.service
Before=shutdown.target
Conflicts=shutdown.target

[Service]
Type=oneshot
RemainAfterExit=yes
# A missing or emptied backing file must fail here, not produce a half-built
# volume group.
ExecStartPre=/usr/bin/test -s %s
# Idempotent: also what a repaired boot runs.
ExecStart=/bin/sh -c 'losetup -j %s | grep -q . || losetup --find --show %s'
ExecStart=/sbin/vgchange -ay %s
ExecStop=/bin/sh -c 'vgchange -an %s || true'
ExecStop=/bin/sh -c 'd=$(losetup -j %s | cut -d: -f1); [ -n "$d" ] && losetup -d "$d" || true'

[Install]
WantedBy=multi-user.target
`, DefaultMountUnit, spec.ImagePath, spec.ImagePath, spec.ImagePath, spec.VG, spec.VG, spec.ImagePath)
}

// mountUnit mounts the data volume, before local-fs.target so that everything
// which consumes /var/stack/data is ordered behind it without a chain of
// per-service overrides.
func mountUnit(spec Spec) string {
	requires := ""
	if spec.Mode == ModeLoop {
		requires = "Requires=" + DefaultLoopUnit + "\nAfter=" + DefaultLoopUnit + "\n"
	}
	return fmt.Sprintf(`[Unit]
# Generated by pmcluster. Do not edit: `+"`pmcluster storage provision`"+` rewrites this file.
Description=pmcluster app data (%s)
Documentation=https://github.com/hazemarian/poor-man-cluster
%s# A failed mount must fail the unit: mounting nothing and carrying on is how a
# node ends up serving empty directories.
#
# Deliberately NOT Before=local-fs.target. The backing file lives on /var, which
# local-fs.target mounts, so ordering this mount before local-fs.target is a
# dependency cycle — and systemd breaks cycles silently, by deleting the mount
# job. Consumers wait for this unit explicitly via RequiresMountsFor.
DefaultDependencies=no
Conflicts=umount.target
Before=umount.target

[Mount]
What=%s
Where=%s
Type=ext4
# noatime: the hourly archive walk reads every file once and should not write
# atime updates back into the volume it is snapshotting.
Options=defaults,noatime

[Install]
WantedBy=multi-user.target
`, spec.VolumeRoot, requires, spec.device(), spec.VolumeRoot)
}

// dockerDropIn makes docker depend on the mount.
func dockerDropIn(spec Spec) string {
	return fmt.Sprintf(`# Generated by pmcluster. Do not edit.
#
# docker must not start without the app-data mount. Without this, a boot where
# the data volume failed leaves /var/stack/data as an ordinary directory, docker
# comes up anyway, and every stack's bind mount silently points at an empty
# directory. RequiresMountsFor adds Requires= and After= on the mount unit: no
# mount, no docker, and the node stays visibly out of service instead of serving
# blank databases.
[Unit]
RequiresMountsFor=%s
`, spec.VolumeRoot)
}

// consumerDropIn makes any unit that reads stack data wait for the mount.
// Without it, a daemon that starts before the volume is mounted deploys stacks
// with bind mounts pointing at an empty directory on the root filesystem.
func consumerDropIn(spec Spec, who string) string {
	return fmt.Sprintf(`# Generated by pmcluster. Do not edit.
#
# %s must not run before the app-data volume exists: it would create
# directories and deploy stacks pointing at an empty path on the root
# filesystem.
[Unit]
RequiresMountsFor=%s
`, who, spec.VolumeRoot)
}

// writeUnits installs the rendered files and brings the volume up.
func writeUnits(ctx context.Context, spec Spec, res *Result) error {
	for name, content := range UnitFiles(spec) {
		path := filepath.Join(spec.UnitDir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return fmt.Errorf("create unit dir for %s: %w", name, err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return fmt.Errorf("write unit %s: %w", name, err)
		}
		res.UnitsWritten = append(res.UnitsWritten, path)
	}

	// The mount point itself must exist before the unit can mount onto it.
	if err := os.MkdirAll(spec.VolumeRoot, 0o755); err != nil {
		return fmt.Errorf("create mount point %s: %w", spec.VolumeRoot, err)
	}

	// One verb per invocation: systemctl takes a single verb, and passing
	// "daemon-reload enable <unit>" silently misparses instead of complaining.
	units := []string{DefaultMountUnit}
	if spec.Mode == ModeLoop {
		units = append([]string{DefaultLoopUnit}, units...)
	}
	for _, argv := range [][]string{
		{"daemon-reload"},
		{"enable", DefaultLoopUnit},
		{"enable", DefaultMountUnit},
	} {
		if spec.Mode != ModeLoop && argv[1] == DefaultLoopUnit {
			continue
		}
		if out, err := spec.exec(ctx, "systemctl", argv...); err != nil {
			return fmt.Errorf("systemctl %s: %w (%s)", strings.Join(argv, " "), err, strings.TrimSpace(string(out)))
		}
	}
	_ = units
	// start, not restart: on a re-run the mount is already active and starting
	// it again is a no-op.
	if out, err := spec.exec(ctx, "systemctl", "start", DefaultMountUnit); err != nil {
		return fmt.Errorf("mount %s: %w (%s) — the units are installed, so this will retry at the next boot", spec.VolumeRoot, err, strings.TrimSpace(string(out)))
	}

	// Prove it, rather than trusting systemctl's exit code.
	after, err := detect(ctx, spec)
	if err != nil {
		return err
	}
	if !after.Provisioned() {
		return fmt.Errorf("provisioned %s but %s is still not mounted from it", spec.device(), spec.VolumeRoot)
	}
	return nil
}

// Uninstall removes the units. The volume and its data are left alone: a
// storage teardown that deletes data is a footgun, not a feature.
func Uninstall(ctx context.Context, spec Spec) error {
	spec = spec.withDefaults()
	if out, err := spec.exec(ctx, "systemctl", "disable", "--now", DefaultMountUnit, DefaultLoopUnit); err != nil {
		return fmt.Errorf("systemctl disable: %w (%s)", err, strings.TrimSpace(string(out)))
	}
	for name := range UnitFiles(spec) {
		if err := os.Remove(filepath.Join(spec.UnitDir, name)); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("remove unit %s: %w", name, err)
		}
	}
	_, _ = spec.exec(ctx, "systemctl", "daemon-reload")
	return nil
}
